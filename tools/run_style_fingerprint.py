def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--match", default="all", help="'all' or a single match id")
    ap.add_argument("--out", default="results/style_fingerprint_v1.md")
    args = ap.parse_args()
    ids = MATCHES if args.match == "all" else [args.match]
    res = build(ids)
    write_report(res, Path(args.out))


if __name__ == "__main__":
    main()
