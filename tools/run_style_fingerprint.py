"""Run the tracking-native style fingerprint v1 (Plan B-4) across the processed ManU matches.

Computes, per team-match: the phase profile, the counter-press table, and the sliced-Wasserstein
frame-embedding stack; then the 6x6 prototype-Wasserstein distance matrix over the six team-match
sides and writes ``results/style_fingerprint_v1.md``.

Run:
    python tools/run_style_fingerprint.py --match all
    python tools/run_style_fingerprint.py --match brighton_manutd
"""

