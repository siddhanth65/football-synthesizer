# 149084 team-0 player rows vs 670 team-1 (balance 0.004) -- ~all players fell into one team, so it
# yields only one (meaningless, 22-player-blob) side. It is excluded from the two-team analytics;
# re-anchoring is a generator (team_anchor) fix, out of scope for this analytics pass.
EXCLUDED = {"southampton_manutd": "team-anchor collapse (0.004 balance) -> one usable side"}
MATCHES = ["brighton_manutd", "manutd_liverpool", "manutd_fulham", "palace_manutd",
           "manutd_tottenham"]
SHORT = {"brighton_manutd": "Bri", "manutd_liverpool": "Liv", "manutd_fulham": "Ful",
         "palace_manutd": "Pal", "southampton_manutd": "Sou", "manutd_tottenham": "Tot"}
MANU = "Man Utd"


def side_labels(match) -> dict[int, str]:
    """``team_index -> side label``; ManU tagged with the opponent, opponent by its own name.

    ManU is the anchored team 0 in the four home fixtures but team 1 at Palace and Southampton, so the
    ManU index is resolved from ``match.teams`` rather than assumed.
    """
    mi = match.teams.index(MANU)
    return {mi: f"ManU_v{SHORT[match.id]}", 1 - mi: match.teams[1 - mi]}


def _fmt(df: pd.DataFrame, ndp: int = 3) -> str:
    return df.round(ndp).to_string(index=False)


def build(match_ids: list[str]) -> dict:
    """Compute phase profiles, counter-press tables, and embedding sides for the given matches."""
    phase_rows, cp_rows, sides = [], [], {}
    for mid in match_ids:
        m = registry.get(mid)
        labels = side_labels(m)
        pp = sf.phase_profile(m)
        pp.insert(0, "side", pp["team"].map(labels))
        phase_rows.append(pp.drop(columns="team"))
        cp = sf.counterpress(m)
        cp.insert(0, "side", cp["team"].map(labels))
        cp_rows.append(cp.drop(columns="team"))
        for center in (False, True):
            emb = sf.match_embeddings(m, center=center)
            for t, mat in emb.items():
                sides.setdefault(center, {})[labels[t]] = mat
        print(f"[{mid}] phases={len(pp)} rows, counter-press sides={len(cp)}, "
              f"frames={ {labels[t]: len(v) for t, v in emb.items()} }")
    return {
        "phase": pd.concat(phase_rows, ignore_index=True),
        "cp": pd.concat(cp_rows, ignore_index=True),
        "dist": {c: sf.distance_matrix(sides[c]) for c in sides},
    }


def identity_signals(dist: pd.DataFrame) -> dict:
    """Intra-ManU vs ManU-to-opponent mean distance + each ManU side's nearest neighbour."""
    manu = [s for s in dist.index if s.startswith("ManU")]
    opp = [s for s in dist.index if not s.startswith("ManU")]
    intra = [dist.loc[a, b] for i, a in enumerate(manu) for b in manu[i + 1:]]
    cross = [dist.loc[a, b] for a in manu for b in opp]
    nn = {a: dist.loc[a].drop(a).idxmin() for a in dist.index}
    return {"intra_manu": float(np.mean(intra)), "manu_to_opp": float(np.mean(cross)),
            "nearest": nn}


